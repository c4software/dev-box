# shellcheck shell=bash
# dev-box: an iOS app of an Xcode project, built, signed, installed and
# launched on Linux. Sourced by dev-box-ios for `devbox ios xcode`, not run.
#
# It leans on omarchy-apple-dev as far as it goes: xcodeproj2xtool.py turns
# the app target into an xtool package, ship.sh --device builds it the way
# Xcode lays an app out (app icon, resources at the root of the .app for
# Bundle.main), provision-dev.py and sign-dev.sh sign it. What none of them
# does is made up for here, each part found on a real app (SwiftUI, Firebase,
# RxSwift, a private package):
#   - the settings of one configuration (Debug by default), where the
#     generator only reads Release: identifier, name, version, Info.plist;
#   - manifests that test the machine SwiftPM runs on (canImport(Darwin),
#     os(Linux), os(macOS)): RxSwift leaves RxCocoa out on Linux. Those
#     packages are copied next to the build, the tests answered as on a Mac,
#     and declared by path in their place;
#   - the SwiftUI and UIKit shortcuts of the asset symbols (Color.name,
#     UIColor(.name)), which Xcode writes and the actool of the box does not;
#     the symbols themselves need iOS 17, so the package targets it at least;
#   - code built as a package (SWIFT_PACKAGE, the files of SwiftGen) reads
#     the Info.plist of the resource bundle, which gets the keys of the app's;
#   - the signature for the device plugged in: the profile of xtool install
#     holds the first 20 devices of the team only; pymobiledevice3 installs,
#     stops the open app first and launches.
#
# It also runs as root (docker exec -u 0 from the host): with rootless Docker,
# root in the box is the user of the host, the only one that may write into a
# project mounted from it. It then takes the tools of the box's user, its SDK
# and its Apple sign-in through links in /root (inside the container only).

# shellcheck source=/usr/share/devbox/lib/ios-kmp.sh
. /usr/share/devbox/lib/ios-kmp.sh

IOS_XCODE_PY="${IOS_XCODE_PY:-/usr/share/devbox/lib/ios-xcode.py}"

ios_xcode_usage() {
  cat <<'EOF'
Usage: devbox ios xcode [project dir] [step] [options]

Builds the app of an Xcode project on Linux, then installs and launches it
on the iPhone or iPad plugged in. Steps:
  run       build, install and launch (the default)
  project   the xtool package generated from the .xcodeproj
  build     the app and its .ipa, unsigned
  install   signed for the device plugged in, then installed
  launch    launched, the running one stopped first
  logs      the logs of the app on the device

Options:
  --project App.xcodeproj    the project (the only one in the dir otherwise)
  --target name              the app target (when the project has several)
  --configuration name       the build configuration (Debug)
  --package name=path[@ref]  a dependency taken from a local git copy, at
                             the commit of ref (its current one otherwise),
                             in place of the one the project names (a
                             private repository, a branch not pushed yet)
  --signed-id id             the identifier the app is signed under
                             (XTL-<team key>.<identifier>, like xtool, so it
                             never replaces the App Store or TestFlight one)
  --out dir                  where it all goes (<dir>/build/devbox-ios)

Customizing:
  What Xcode does and the generated package does not is made up for on its
  own, each part with an option to tune or turn it off:
  --min-ios version          the lowest iOS the package targets (17.0): the
                             asset symbols of the box's actool need 17
  --no-darwin-manifests      keep the manifests that test the build machine
                             (canImport(Darwin), os(Linux), os(macOS)) as
                             they are; by default they are answered as on a
                             Mac, in a copy under <out>/deps
  --no-asset-extensions      no Color.name, UIColor.name, Image.name,
                             UIImage.name; by default they follow the
                             project's ASSETCATALOG_COMPILER_GENERATE_SWIFT_
                             ASSET_SYMBOL_EXTENSIONS (on unless NO)
  The build itself is ship.sh --device of omarchy-apple-dev (app icon,
  resources at the root of the .app); the app's Info.plist keys are then
  added to the one of its resource bundle (code built as a package reads
  Bundle.module). ROOT_RESOURCES and the other variables of ship.sh apply.
  Anything else: run the steps one by one and change the package between
  project and build, under <out>/xtool (regenerated by each project step).
  A project that needs it every time wraps the command in a script of its
  own: the options above, then its own changes between the steps.

Environment:
  ASC_KEY_ID, ASC_ISSUER_ID  the App Store Connect API key used to sign,
  ASC_KEY_PATH               read from xtool auth status when unset
  USER_NAME                  as root, the box's user whose tools are taken

Needs the ios environment, its SDK and the Apple sign-in with an App Store
Connect API key (devbox help ios), and a device paired through usbmuxd. As
root, it takes the tools, the SDK and the sign-in of the box's user. The
details: docs/dev-envs.md of dev-box, devbox help ios.
EOF
}

ios_xcode_log() { printf '\033[1m[devbox ios xcode]\033[0m %s\n' "$*"; }
ios_xcode_die() {
  echo "devbox ios xcode: $*" >&2
  exit 1
}

# xtool (SwiftNIO) aborts when its standard input is a file or /dev/null:
# it gets a pipe that stays open while it runs, the outputs of the sleep
# closed so that a pipe after xtool still ends.
ios_xcode_xtool() {
  xtool "$@" < <(exec sleep 86400 >/dev/null 2>&1)
}

ios_xcode_py() {
  OAD_TOOLS="$OAD_DIR/tools" python3 "$IOS_XCODE_PY" "$@"
}

# As root: the tools of the box's user (ios_kmp_root_env), and its SDK and
# Apple sign-in where swift and xtool of root look for them.
ios_xcode_root_env() {
  IOS_XCODE_HOME="$HOME"
  [ "$(id -u)" = 0 ] || return 0
  ios_kmp_root_env
  local home pair
  home="$(getent passwd "${USER_NAME:-dev}" | cut -d: -f6)"
  [ -n "$home" ] && [ "$home" != "$HOME" ] || return 0
  IOS_XCODE_HOME="$home"
  for pair in .swiftpm/swift-sdks .config/xtool .appstoreconnect pymobile3-venv; do
    [ -e "$home/$pair" ] || continue
    [ "$(readlink "$HOME/$pair" 2>/dev/null)" = "$home/$pair" ] && continue
    mkdir -p "$(dirname "$HOME/$pair")"
    rm -rf "${HOME:?}/$pair"
    ln -s "$home/$pair" "$HOME/$pair"
  done
  # Projects mounted from the host belong to another user: git reads them anyway.
  export GIT_CONFIG_COUNT=1 GIT_CONFIG_KEY_0=safe.directory GIT_CONFIG_VALUE_0='*'
}

ios_xcode_setting() {
  ios_xcode_py setting "$IOS_XCODE_PROJECT" "$IOS_XCODE_CONFIGURATION" "${IOS_XCODE_TARGET:--}" "$1"
}

# .package(...) of a --package name=path[@ref]: a git copy read at a commit
# (nothing written into it), a plain directory by path.
ios_xcode_local_dependency() {
  local spec="$1" path ref revision
  path="${spec%@*}"
  ref=""
  [ "$path" = "$spec" ] || ref="${spec##*@}"
  path="$(cd "$path" 2>/dev/null && pwd)" || ios_xcode_die "--package: no such directory: ${spec%@*}"
  if git -C "$path" rev-parse --git-dir >/dev/null 2>&1; then
    revision="$(git -C "$path" rev-parse --verify -q "${ref:-HEAD}^{commit}" ||
      git -C "$path" rev-parse --verify -q "origin/$ref^{commit}")" ||
      ios_xcode_die "--package: no commit $ref in $path"
    echo ".package(url: \"file://$path\", revision: \"$revision\")"
  else
    echo ".package(path: \"$path\")"
  fi
}

ios_xcode_product() { sed -n 's/^product: *//p' "$IOS_XCODE_PKG/xtool.yml"; }

ios_xcode_project() {
  local pkg="$IOS_XCODE_PKG" spec name replacements=() product
  ios_xcode_log "xtool package from $(basename "$IOS_XCODE_PROJECT") ($IOS_XCODE_CONFIGURATION)"
  # .build stays: the packages fetched and built are kept from one run to the next.
  mkdir -p "$pkg"
  find "$pkg" -mindepth 1 -maxdepth 1 ! -name .build ! -name xtool -exec rm -rf {} +
  ios_xcode_py convert "$IOS_XCODE_PROJECT" "$pkg" "$IOS_XCODE_CONFIGURATION" \
    ${IOS_XCODE_TARGET:+--target "$IOS_XCODE_TARGET"} 2>&1 | grep -v '^APP_ICON=' || true
  [ -f "$pkg/Package.swift" ] || ios_xcode_die "no package generated"

  for spec in "${IOS_XCODE_PACKAGES[@]}"; do
    name="${spec%%=*}"
    replacements+=("$name=$(ios_xcode_local_dependency "${spec#*=}")")
  done
  ios_xcode_py package "$pkg/Package.swift" "$IOS_XCODE_MIN_IOS" "${replacements[@]}"

  # Manifests that answer for Linux: copied, answered as on a Mac, by path.
  if [ "$IOS_XCODE_DARWIN_MANIFESTS" = true ]; then
    ios_xcode_log "packages fetched (swift package resolve)"
    (cd "$pkg" && swift package resolve >/dev/null) || ios_xcode_die "swift package resolve failed in $pkg"
    replacements=()
    local kind
    while read -r name kind; do
      [ -n "$name" ] || continue
      if [ "$kind" != direct ]; then
        ios_xcode_log "$name: its manifest tests the build machine, left as is (a dependency of a dependency)"
        continue
      fi
      ios_xcode_log "$name: its manifest tests the build machine, answered as on a Mac"
      rm -rf "$IOS_XCODE_OUT/deps/$name"
      mkdir -p "$IOS_XCODE_OUT/deps"
      cp -R "$pkg/.build/checkouts/$name" "$IOS_XCODE_OUT/deps/$name"
      rm -rf "$IOS_XCODE_OUT/deps/$name/.git"
      ios_xcode_py patch-manifests "$IOS_XCODE_OUT/deps/$name"
      replacements+=("$name=.package(path: \"../deps/$name\")")
    done < <(ios_xcode_py darwin-manifests "$pkg/.build/checkouts" "$pkg/Package.swift")
    if [ "${#replacements[@]}" -gt 0 ]; then
      ios_xcode_py package "$pkg/Package.swift" "$IOS_XCODE_MIN_IOS" "${replacements[@]}"
      (cd "$pkg" && swift package resolve >/dev/null) || ios_xcode_die "swift package resolve failed in $pkg"
    fi
  fi

  product="$(ios_xcode_product)"
  if [ "$IOS_XCODE_ASSET_EXTENSIONS" = true ] &&
    [ "$(ios_xcode_setting ASSETCATALOG_COMPILER_GENERATE_SWIFT_ASSET_SYMBOL_EXTENSIONS)" != NO ]; then
    local catalogs=()
    while IFS= read -r name; do catalogs+=("$pkg/Sources/$product/$name"); done < <(ios_xcode_py catalogs "$pkg/Package.swift")
    [ "${#catalogs[@]}" -eq 0 ] ||
      ios_xcode_py symbols "$pkg/Sources/$product/DevboxAssetSymbolExtensions.swift" "${catalogs[@]}"
  fi
  ios_xcode_log "package: $pkg"
}

ios_xcode_build() {
  local pkg="$IOS_XCODE_PKG" product app bundle config=debug
  [ -f "$pkg/Package.swift" ] || ios_xcode_project
  product="$(ios_xcode_product)"
  case "${IOS_XCODE_CONFIGURATION,,}" in *release*) config=release ;; esac
  # ship.sh --device of omarchy-apple-dev: xtool dev build, then what Xcode
  # does next and xtool does not (the app icon, the resources at the root of
  # the .app for Bundle.main, the placeholder check). Unsigned.
  ios_xcode_log "$product ($config, ship.sh --device; the first build fetches and builds every package, minutes)"
  (cd "$pkg" && ulimit -n 65536 && CONFIGURATION="$config" ship.sh --device < <(exec sleep 86400 >/dev/null 2>&1) 2>&1 | cat)
  app="$pkg/xtool/$product.app"
  [ -x "$app/$product" ] || ios_xcode_die "no app built: $app"

  # Code built as a package (SWIFT_PACKAGE, the files SwiftGen generates)
  # reads the Info.plist of the resource bundle: it gets the app's keys.
  bundle="$app/${product}_${product}.bundle"
  [ ! -d "$bundle" ] || ios_xcode_py merge-plist "$app/Info.plist" "$bundle/Info.plist"
  rm -rf "$IOS_XCODE_OUT/Payload" "$IOS_XCODE_OUT/$product.ipa"
  mkdir -p "$IOS_XCODE_OUT/Payload"
  cp -R "$app" "$IOS_XCODE_OUT/Payload/"
  (cd "$IOS_XCODE_OUT" && zip -qry "$product.ipa" Payload && rm -rf Payload)
  ios_xcode_log "app: $IOS_XCODE_OUT/$product.ipa (unsigned)"
}

ios_xcode_usbmuxd() {
  if [ "$(id -u)" = 0 ]; then usbmuxd; else sudo usbmuxd; fi
}

# The UDID of the device plugged in. usbmuxd started when it is not running,
# restarted once when it no longer sees a device that was unplugged.
ios_xcode_device() {
  local udid
  pgrep -x usbmuxd >/dev/null || ios_xcode_usbmuxd
  udid="$(ios_xcode_xtool devices 2>&1 | sed -n 's/.*\[usb\]: *//p' | head -n 1)"
  if [ -z "$udid" ]; then
    ios_xcode_log "no device seen: usbmuxd restarted" >&2
    if [ "$(id -u)" = 0 ]; then pkill -x usbmuxd || true; else sudo pkill -x usbmuxd || true; fi
    sleep 2
    ios_xcode_usbmuxd
    sleep 3
    udid="$(ios_xcode_xtool devices 2>&1 | sed -n 's/.*\[usb\]: *//p' | head -n 1)"
  fi
  [ -n "$udid" ] || ios_xcode_die "no device over USB: plugged in, unlocked, trusted (devbox help ios, step 2)"
  echo "$udid"
}

# The API key xtool auth signed in with: ASC_KEY_ID, ASC_ISSUER_ID, ASC_KEY_PATH.
ios_xcode_api_key() {
  local status keys
  status="$(ios_xcode_xtool auth status 2>&1 | cat)"
  export ASC_KEY_ID="${ASC_KEY_ID:-$(sed -n 's/.*ASC key ID: *//p' <<<"$status")}"
  export ASC_ISSUER_ID="${ASC_ISSUER_ID:-$(sed -n 's/.*Issuer ID: *//p' <<<"$status")}"
  [ -n "$ASC_KEY_ID" ] && [ -n "$ASC_ISSUER_ID" ] ||
    ios_xcode_die "xtool is not signed in with an App Store Connect API key: xtool auth login --mode key"
  keys=("$IOS_XCODE_HOME"/.appstoreconnect/private_keys/AuthKey_"$ASC_KEY_ID".p8 "$IOS_XCODE_HOME"/.appstoreconnect/AuthKey_"$ASC_KEY_ID".p8)
  if [ -z "${ASC_KEY_PATH:-}" ]; then
    for ASC_KEY_PATH in "${keys[@]}"; do [ -f "$ASC_KEY_PATH" ] && break; done
  fi
  export ASC_KEY_PATH
  [ -f "$ASC_KEY_PATH" ] || ios_xcode_die "no key file AuthKey_$ASC_KEY_ID.p8 in ~/.appstoreconnect"
}

ios_xcode_bundle_id() {
  python3 -c 'import plistlib, sys; print(plistlib.load(open(sys.argv[1], "rb"))["CFBundleIdentifier"])' \
    "$IOS_XCODE_PKG/xtool/$(ios_xcode_product).app/Info.plist"
}

ios_xcode_install() {
  local product udid id dev tools venv stage
  product="$(ios_xcode_product 2>/dev/null)"
  [ -n "$product" ] && [ -f "$IOS_XCODE_OUT/$product.ipa" ] || ios_xcode_build
  product="$(ios_xcode_product)"
  udid="$(ios_xcode_device)"
  ios_xcode_api_key
  if [ -n "$IOS_XCODE_SIGNED_ID" ]; then
    id="$IOS_XCODE_SIGNED_ID"
  else
    id="XTL-${ASC_ISSUER_ID:0:8}"
    id="${id^^}.$(ios_xcode_bundle_id)"
  fi
  dev="$IOS_XCODE_HOME/.config/omarchy-apple-dev/development"
  tools="$OAD_DIR/tools"
  venv="$IOS_XCODE_HOME/pymobile3-venv/bin/python3"
  ios_xcode_log "development profile for $id on $udid"
  "$venv" "$tools/provision-dev.py" --bundle-id "$id" --udid "$udid" --out "$dev" | grep -v 'Entitlements' || true
  stage="$IOS_XCODE_OUT/signing"
  rm -rf "$stage"
  mkdir -p "$stage"
  (cd "$stage" && unzip -q "$IOS_XCODE_OUT/$product.ipa")
  ios_xcode_py set-plist "$stage/Payload/$product.app/Info.plist" CFBundleIdentifier "$id"
  ios_xcode_log "signed (rcodesign)"
  "$tools/sign-dev.sh" "$stage/Payload/$product.app" "$stage/$product.ipa" "$dev" | tail -n 1
  ios_xcode_stop "$udid" "$product"
  ios_xcode_log "installed on $udid"
  pymobiledevice3 apps install --udid "$udid" "$stage/$product.ipa"
  echo "$id" >"$IOS_XCODE_OUT/signed-id"
}

# The app stopped when it runs (process named after the executable): installing
# over an open app, or launching it, otherwise leaves the old one stuck on the
# device until it is closed by hand. The developer disk image dvt needs is
# mounted first, once per start of the device.
ios_xcode_stop() {
  local udid="$1" product="$2" pid
  pymobiledevice3 mounter list --udid "$udid" 2>/dev/null | grep -qi personalized ||
    pymobiledevice3 mounter auto-mount --udid "$udid"
  for pid in $(pymobiledevice3 developer dvt proclist --userspace --udid "$udid" 2>/dev/null | python3 -c '
import json, sys
for p in json.load(sys.stdin):
    if p.get("name") == sys.argv[1]:
        print(p["pid"])' "$product"); do
    ios_xcode_log "running one stopped (pid $pid)"
    pymobiledevice3 developer dvt kill "$pid" --userspace --udid "$udid"
  done
}

ios_xcode_launch() {
  local product udid id
  product="$(ios_xcode_product)"
  udid="$(ios_xcode_device)"
  id="$(cat "$IOS_XCODE_OUT/signed-id" 2>/dev/null)" || ios_xcode_die "not installed yet: devbox ios xcode install"
  ios_xcode_stop "$udid" "$product"
  ios_xcode_log "launching $id"
  pymobiledevice3 developer dvt launch "$id" --userspace --udid "$udid"
}

ios_xcode_logs() {
  local udid
  udid="$(ios_xcode_device)"
  pymobiledevice3 syslog live --udid "$udid" --process-name "$(ios_xcode_product)"
}

ios_xcode() {
  local dir="." step=run
  IOS_XCODE_PROJECT="" IOS_XCODE_TARGET="" IOS_XCODE_CONFIGURATION=Debug IOS_XCODE_SIGNED_ID="" IOS_XCODE_OUT=""
  IOS_XCODE_PACKAGES=()
  IOS_XCODE_MIN_IOS="17.0" IOS_XCODE_DARWIN_MANIFESTS=true IOS_XCODE_ASSET_EXTENSIONS=true
  while [ $# -gt 0 ]; do
    case "$1" in
    --min-ios) IOS_XCODE_MIN_IOS="${2:?--min-ios needs a version}" && shift ;;
    --no-darwin-manifests) IOS_XCODE_DARWIN_MANIFESTS=false ;;
    --no-asset-extensions) IOS_XCODE_ASSET_EXTENSIONS=false ;;
    --project) IOS_XCODE_PROJECT="${2:?--project needs a path}" && shift ;;
    --target) IOS_XCODE_TARGET="${2:?--target needs a name}" && shift ;;
    --configuration) IOS_XCODE_CONFIGURATION="${2:?--configuration needs a name}" && shift ;;
    --package)
      case "${2:-}" in *=*) IOS_XCODE_PACKAGES+=("$2") ;; *) ios_xcode_die "--package name=path[@ref]" ;; esac
      shift
      ;;
    --signed-id) IOS_XCODE_SIGNED_ID="${2:?--signed-id needs an identifier}" && shift ;;
    --out) IOS_XCODE_OUT="${2:?--out needs a dir}" && shift ;;
    run | project | build | install | launch | logs) step="$1" ;;
    -*) ios_xcode_die "unknown option $1 (devbox ios xcode --help)" ;;
    *)
      [ -d "$1" ] || ios_xcode_die "no such project dir or step: $1"
      dir="$1"
      ;;
    esac
    shift
  done
  dir="$(cd "$dir" && pwd)"
  if [ -z "$IOS_XCODE_PROJECT" ]; then
    local found=("$dir"/*.xcodeproj)
    [ -d "${found[0]}" ] || ios_xcode_die "no .xcodeproj in $dir (--project)"
    [ "${#found[@]}" -eq 1 ] || ios_xcode_die "several .xcodeproj in $dir: pick one with --project"
    IOS_XCODE_PROJECT="${found[0]}"
  fi
  IOS_XCODE_PROJECT="$(cd "$(dirname "$IOS_XCODE_PROJECT")" && pwd)/$(basename "$IOS_XCODE_PROJECT")"
  IOS_XCODE_OUT="${IOS_XCODE_OUT:-$dir/build/devbox-ios}"
  mkdir -p "$IOS_XCODE_OUT"
  IOS_XCODE_OUT="$(cd "$IOS_XCODE_OUT" && pwd)"
  IOS_XCODE_PKG="$IOS_XCODE_OUT/xtool"
  [ -f "$OAD_DIR/tools/xcodeproj2xtool.py" ] || ios_xcode_die "omarchy-apple-dev has no xcodeproj2xtool.py: devbox dev-env ios"
  mise x swift -- swift sdk list 2>/dev/null | grep -qx darwin ||
    ios_xcode_die "no iOS SDK: devbox ios sdk"
  case "$step" in
  project) ios_xcode_project ;;
  build)
    ios_xcode_project
    ios_xcode_build
    ;;
  install) ios_xcode_install ;;
  launch) ios_xcode_launch ;;
  logs) ios_xcode_logs ;;
  run)
    ios_xcode_project
    ios_xcode_build
    ios_xcode_install
    ios_xcode_launch
    ;;
  esac
}
